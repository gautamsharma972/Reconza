using ClosedXML.Excel;
using SettleFlow.Core.Engine;
using SettleFlow.Core.Model;

namespace SettleFlow.Core.Reporting;

public sealed record ReportContext(string WorkflowName, string RunLabel, DateTimeOffset GeneratedAt, string GeneratedBy,
    IReadOnlyDictionary<string, string> SourceFiles);

public static class ExcelReportWriter
{
    /// <summary>
    /// Neutralizes spreadsheet formula injection (CSV/Excel "DDE" attacks): any text that a spreadsheet
    /// could interpret as a formula is prefixed with an apostrophe.
    /// </summary>
    public static string SafeText(string? s)
    {
        if (string.IsNullOrEmpty(s)) return "";
        return s[0] is '=' or '+' or '-' or '@' or '\t' or '\r' or '\n' or '|' or '%' ? "'" + s : s;
    }

    public static void Write(RunResult result, ReportContext ctx, Stream output)
    {
        var def = result.Definition;
        var tpl = def.Report;
        using var wb = new XLWorkbook();
        var money = tpl.CurrencyFormat;

        // ---- Summary
        var sum = wb.AddWorksheet("Summary");
        sum.Cell(1, 1).SetValue(SafeText(tpl.Title)).Style.Font.SetBold().Font.SetFontSize(16);
        var r = 3;
        void Kv(string k, XLCellValue v) { sum.Cell(r, 1).SetValue(k).Style.Font.SetBold(); sum.Cell(r, 2).SetValue(v); r++; }
        Kv("Workflow", SafeText(ctx.WorkflowName));
        Kv("Run", SafeText(ctx.RunLabel));
        Kv("Generated", ctx.GeneratedAt.ToString("yyyy-MM-dd HH:mm 'UTC'"));
        Kv("Generated by", SafeText(ctx.GeneratedBy));
        r++;
        sum.Cell(r, 1).SetValue("Source"); sum.Cell(r, 2).SetValue("File"); sum.Cell(r, 3).SetValue("Role");
        sum.Cell(r, 4).SetValue("Rows read"); sum.Cell(r, 5).SetValue("Included"); sum.Cell(r, 6).SetValue("Excluded"); sum.Cell(r, 7).SetValue("Total");
        sum.Range(r, 1, r, 7).Style.Font.SetBold().Fill.SetBackgroundColor(XLColor.FromHtml("#E8EEF7"));
        r++;
        foreach (var s in def.Sources)
        {
            var st = result.Stats[s.Name];
            sum.Cell(r, 1).SetValue(SafeText(s.Name));
            sum.Cell(r, 2).SetValue(SafeText(ctx.SourceFiles.GetValueOrDefault(s.Name, "")));
            sum.Cell(r, 3).SetValue(s.Role.ToString());
            sum.Cell(r, 4).SetValue(st.RowsRead);
            sum.Cell(r, 5).SetValue(st.RowsIncluded);
            sum.Cell(r, 6).SetValue(st.RowsExcluded);
            sum.Cell(r, 7).SetValue(st.Total).Style.NumberFormat.SetFormat(money);
            r++;
        }
        r++;
        Kv(tpl.NetLabel + " (all groups)", result.NetTotal);
        sum.Cell(r - 1, 2).Style.NumberFormat.SetFormat(money).Font.SetBold();
        Kv("Groups settled", result.Lines.Count);
        Kv("Exceptions", result.Exceptions.Count);
        foreach (var g in result.Exceptions.GroupBy(e => e.Type).OrderBy(g => g.Key))
            Kv("  " + g.Key, g.Count());
        sum.Columns().AdjustToContents(1, 60);

        // ---- Settlement
        var set = wb.AddWorksheet("Settlement");
        var moneySources = def.Sources.Where(s => s.AmountField is not null && s.Role != SourceRole.ReferenceOnly).ToList();
        var c = 1;
        var moneyCols = new HashSet<int>();
        set.Cell(1, c++).SetValue(SafeText(tpl.GroupLabel));
        foreach (var s in moneySources)
        {
            var label = tpl.SourceLabels.GetValueOrDefault(s.Name, s.Name);
            set.Cell(1, c++).SetValue(SafeText($"{label} (count)"));
            moneyCols.Add(c);
            set.Cell(1, c++).SetValue(SafeText(s.Role == SourceRole.Deduction ? $"{label} (−)" : label));
        }
        moneyCols.Add(c);
        set.Cell(1, c++).SetValue(SafeText(tpl.NetLabel));
        set.Cell(1, c).SetValue("Open exceptions");
        var lastCol = c;
        set.Range(1, 1, 1, lastCol).Style.Font.SetBold().Fill.SetBackgroundColor(XLColor.FromHtml("#E8EEF7"));

        var row = 2;
        foreach (var line in result.Lines)
        {
            c = 1;
            set.Cell(row, c++).SetValue(SafeText(line.Group));
            foreach (var s in moneySources)
            {
                set.Cell(row, c++).SetValue(line.SourceCounts.GetValueOrDefault(s.Name));
                set.Cell(row, c++).SetValue(line.SourceTotals.GetValueOrDefault(s.Name)).Style.NumberFormat.SetFormat(money);
            }
            set.Cell(row, c++).SetValue(line.Net).Style.NumberFormat.SetFormat(money);
            set.Cell(row, c).SetValue(line.ExceptionCount);
            if (line.ExceptionCount > 0) set.Cell(row, c).Style.Fill.SetBackgroundColor(XLColor.FromHtml("#FFF4CE"));
            row++;
        }
        set.Cell(row, 1).SetValue("Total").Style.Font.SetBold();
        for (var col = 2; col <= lastCol; col++)
        {
            // Totals are computed values, not formulas, so the file is safe to open in any viewer.
            var total = 0m;
            for (var rr = 2; rr < row; rr++) total += set.Cell(rr, col).GetValue<decimal>();
            set.Cell(row, col).SetValue(total).Style.Font.SetBold();
            if (moneyCols.Contains(col)) set.Cell(row, col).Style.NumberFormat.SetFormat(money);
        }
        set.Range(row, 1, row, lastCol).Style.Border.SetTopBorder(XLBorderStyleValues.Thin);
        set.SheetView.FreezeRows(1);
        set.Columns().AdjustToContents(1, 60);

        // ---- Exceptions
        if (tpl.IncludeExceptionsSheet)
        {
            var ex = wb.AddWorksheet("Exceptions");
            string[] hdr = ["Source", "Row", "Type", "Key", "Amount", "Excluded from totals", "Details"];
            for (var i = 0; i < hdr.Length; i++) ex.Cell(1, i + 1).SetValue(hdr[i]);
            ex.Range(1, 1, 1, hdr.Length).Style.Font.SetBold().Fill.SetBackgroundColor(XLColor.FromHtml("#E8EEF7"));
            row = 2;
            foreach (var e in result.Exceptions.OrderBy(e => e.Source).ThenBy(e => e.RowNumber))
            {
                ex.Cell(row, 1).SetValue(SafeText(e.Source));
                if (e.RowNumber is { } rn) ex.Cell(row, 2).SetValue(rn);
                ex.Cell(row, 3).SetValue(e.Type.ToString());
                ex.Cell(row, 4).SetValue(SafeText(e.Key));
                if (e.Amount is { } a) ex.Cell(row, 5).SetValue(a).Style.NumberFormat.SetFormat(money);
                ex.Cell(row, 6).SetValue(e.ExcludedFromTotals ? "Yes" : "No");
                ex.Cell(row, 7).SetValue(SafeText(e.Message));
                row++;
            }
            ex.SheetView.FreezeRows(1);
            if (row > 2) ex.Range(1, 1, row - 1, hdr.Length).SetAutoFilter();
            ex.Columns().AdjustToContents(1, 100);
        }

        // ---- Normalized detail per source (audit trail back to the uploaded rows)
        if (tpl.IncludeDetailSheets)
        {
            foreach (var s in def.Sources)
            {
                var name = SheetName(wb, s.Name);
                var ws = wb.AddWorksheet(name);
                var fields = s.ColumnMap.Keys.Select(k => def.Field(k)).Where(f => f is not null).Cast<FieldDef>().ToList();
                ws.Cell(1, 1).SetValue("Source row");
                ws.Cell(1, 2).SetValue("Status");
                ws.Cell(1, 3).SetValue(SafeText(tpl.GroupLabel));
                for (var i = 0; i < fields.Count; i++) ws.Cell(1, i + 4).SetValue(SafeText(fields[i].Label));
                ws.Range(1, 1, 1, fields.Count + 3).Style.Font.SetBold().Fill.SetBackgroundColor(XLColor.FromHtml("#E8EEF7"));
                row = 2;
                foreach (var nr in result.Rows[s.Name])
                {
                    ws.Cell(row, 1).SetValue(nr.RowNumber);
                    ws.Cell(row, 2).SetValue(!nr.Valid ? "Invalid" : nr.Excluded ? "Excluded" : "Included");
                    ws.Cell(row, 3).SetValue(SafeText(nr.Group));
                    for (var i = 0; i < fields.Count; i++)
                    {
                        var cell = ws.Cell(row, i + 4);
                        switch (nr.Values.GetValueOrDefault(fields[i].Name))
                        {
                            case decimal m: cell.SetValue(m); break;
                            case DateOnly d: cell.SetValue(d.ToDateTime(TimeOnly.MinValue)); cell.Style.DateFormat.SetFormat("yyyy-mm-dd"); break;
                            case string str: cell.SetValue(SafeText(str)); break;
                        }
                    }
                    row++;
                }
                ws.SheetView.FreezeRows(1);
                ws.Columns().AdjustToContents(1, 60);
            }
        }

        wb.SaveAs(output);
    }

    private static string SheetName(XLWorkbook wb, string source)
    {
        var clean = new string(source.Where(ch => ch is not ('\\' or '/' or '?' or '*' or '[' or ']' or ':')).ToArray());
        clean = ("Detail - " + clean).Trim();
        if (clean.Length > 31) clean = clean[..31];
        var name = clean; var n = 2;
        while (wb.Worksheets.Contains(name)) name = $"{clean[..Math.Min(clean.Length, 27)]} ({n++})";
        return name;
    }
}
